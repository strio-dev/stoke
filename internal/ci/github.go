const generatedHeader = "# Generated by Stoke CI. Regenerate instead of editing.\n# stoke-ci-sha256: "
const checkoutAction = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1"

type githubWorkflow struct {
	Name        string            `yaml:"name"`
	On          map[string]any    `yaml:"on"`
	Permissions map[string]string `yaml:"permissions,omitempty"`
	Jobs        yaml.Node         `yaml:"jobs"`
}

type githubContainer struct {
	Image   string `yaml:"image"`
	Options string `yaml:"options,omitempty"`
}

type githubJob struct {
	Container      *githubContainer  `yaml:"container,omitempty"`
	Name           string            `yaml:"name"`
	Needs          []string          `yaml:"needs,omitempty"`
	If             string            `yaml:"if,omitempty"`
	RunsOn         []string          `yaml:"runs-on"`
	TimeoutMinutes int               `yaml:"timeout-minutes"`
	Strategy       *githubStrategy   `yaml:"strategy,omitempty"`
	Env            map[string]string `yaml:"env,omitempty"`
	Outputs        map[string]string `yaml:"outputs,omitempty"`
	Steps          []githubStep      `yaml:"steps"`
}

type githubStrategy struct {
	FailFast    bool                           `yaml:"fail-fast"`
	MaxParallel int                            `yaml:"max-parallel"`
	Matrix      map[string][]map[string]string `yaml:"matrix"`
}

type githubStep struct {
	ID    string         `yaml:"id,omitempty"`
	Name  string         `yaml:"name,omitempty"`
	If    string         `yaml:"if,omitempty"`
	Uses  string         `yaml:"uses,omitempty"`
	With  map[string]any `yaml:"with,omitempty"`
	Shell string         `yaml:"shell,omitempty"`
	Run   string         `yaml:"run,omitempty"`
}

// RenderGitHub emits a separately owned reusable workflow. Caller-owned triggers,
// jobs, permissions and provisioning never need to be parsed or rewritten.
func RenderGitHub(p *Plan, planPath string) ([]byte, error) {
	if err := p.Validate(); err != nil {
		return nil, err
	}
	if err := relativePath(planPath, false); err != nil {
		return nil, fmt.Errorf("CI plan path: %w", err)
	}
	jobs := yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	all := []string{"stoke_context"}
	add := func(id string, job githubJob) error {
		if p.Config.JobContainerImage != "" {
			job.Container = &githubContainer{Image: p.Config.JobContainerImage, Options: p.Config.JobContainerOptions}
		}
		var value yaml.Node
		if err := value.Encode(job); err != nil {
			return err
		}
		jobs.Content = append(jobs.Content, &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: id}, &value)
		return nil
	}
	if err := add("stoke_context", githubJob{Name: "Stoke invocation", RunsOn: p.Config.Runners, TimeoutMinutes: p.Config.TimeoutMinutes,
		Outputs: map[string]string{"scope": "${{ steps.scope.outputs.scope }}"},
		Steps:   []githubStep{{ID: "scope", Name: "Create isolated invocation scope", Shell: "bash", Run: "stoke ci scope --plan-id " + shellQuote(p.ID) + ` --github-output "$GITHUB_OUTPUT"`}},
	}); err != nil {
		return nil, err
	}
	for _, group := range p.Groups {
		job := githubJob{Name: group.Name, Needs: append([]string{"stoke_context"}, group.Needs...), RunsOn: p.Config.Runners, TimeoutMinutes: p.Config.TimeoutMinutes,
			Env: map[string]string{"STOKE_CI_SCOPE": "${{ needs.stoke_context.outputs.scope }}"}, Outputs: map[string]string{}}
		host := false
		for _, selection := range group.Jobs {
			for _, name := range selection.Execute {
				_, requested := p.Host[name]
				host = host || requested
			}
		}
		if host {
			job.Name += " (host)"
			job.Env["STOKE_ALLOW_HOST"] = "${{ inputs.allow_host }}"
			job.Env["STOKE_HOST_CAPABILITIES"] = "${{ inputs.host_capabilities }}"
		}
		for _, dependency := range group.Needs {
			for _, parent := range p.Groups {
				if parent.ID == dependency {
					for _, selection := range parent.Jobs {
						job.Env[InputEnv(selection.OutputKey)] = "${{ needs." + dependency + ".outputs." + selection.OutputKey + " }}"
					}
				}
			}
		}
		for _, selection := range group.Jobs {
			job.Outputs[selection.OutputKey] = "${{ steps.stoke.outputs." + selection.OutputKey + " }}"
		}
		if len(group.Members) == 1 {
			if representative, ok := p.Environments[group.Members[0]]; ok {
				job.Name = "Environment for " + representative
			}
		}
		if p.Config.ResultsRepository != "" {
			job.Env["STOKE_CI_RESULTS_REPOSITORY"] = p.Config.ResultsRepository
		} else if p.RequiresResults {
			job.Env["STOKE_CI_RESULTS_REPOSITORY"] = "${{ inputs.results_repository }}"
		}
		if group.Matrix {
			rows := make([]map[string]string, 0, len(group.Jobs))
			for _, variant := range group.Jobs {
				rows = append(rows, map[string]string{"stoke_job": variant.ID, "stoke_label": matrixLabel(variant)})
			}
			job.Name += " / ${{ matrix.stoke_label }}"
			job.Strategy = &githubStrategy{FailFast: group.FailFast, MaxParallel: group.MaxParallel, Matrix: map[string][]map[string]string{"include": rows}}
			job.Env["STOKE_CI_JOB"] = "${{ matrix.stoke_job }}"
		} else {
			job.Env["STOKE_CI_JOB"] = group.Jobs[0].ID
		}
		run := "stoke ci run --plan " + shellQuote(planPath) + " --plan-id " + shellQuote(p.ID) + ` \
  --job "$STOKE_CI_JOB" \
  --scope "$STOKE_CI_SCOPE" \
  --attempt "$GITHUB_RUN_ATTEMPT" \
  --needs-env \
  --github-output "$GITHUB_OUTPUT" \
  --cache-dir "$RUNNER_TEMP/stoke-cache" \
  --output "$RUNNER_TEMP/stoke-output"`
		if host {
			run = `host_args=()
if [[ "$STOKE_ALLOW_HOST" == true ]]; then
  host_args+=(--allow-host)
fi
` + run + " \\\n  \"${host_args[@]}\" \\\n  --host-capabilities-json \"$STOKE_HOST_CAPABILITIES\""
		}
		if p.RequiresResults || p.Config.ResultsRepository != "" {
			run += " \\\n  --results-repository \"$STOKE_CI_RESULTS_REPOSITORY\""
		}
		for _, repository := range p.Config.CacheFrom {
			run += " \\\n  --cache-from " + shellQuote(repository)
		}
		for _, repository := range p.Config.CacheTo {
			run += " \\\n  --cache-to " + shellQuote(repository)
		}
		if p.Config.Network != "" {
			run += " \\\n  --network " + shellQuote(p.Config.Network)
		}
		job.Steps = []githubStep{
			{Name: "Check out source", Uses: checkoutAction, With: map[string]any{"persist-credentials": false}},
			{ID: "stoke", Name: "Run Stoke job", Shell: "bash", Run: run},
		}
		if err := add(group.ID, job); err != nil {
			return nil, err
		}
		all = append(all, group.ID)
	}
	if err := add("stoke_result", githubJob{Name: "Stoke result", Needs: all, If: "${{ !cancelled() }}", RunsOn: p.Config.Runners, TimeoutMinutes: p.Config.TimeoutMinutes,
		Env:   map[string]string{"STOKE_CI_RESULTS": "${{ toJSON(needs.*.result) }}"},
		Steps: []githubStep{{Name: "Require every generated job to succeed", Shell: "bash", Run: `stoke ci verify-results --results "$STOKE_CI_RESULTS"`}},
	}); err != nil {
		return nil, err
	}
	call := map[string]any{}
	inputs := map[string]any{}
	if p.RequiresResults && p.Config.ResultsRepository == "" {
		inputs["results_repository"] = map[string]any{"type": "string", "required": true, "description": "OCI repository for exact cross-job results; separate from disposable caches"}
	}
	if len(p.Host) != 0 {
		inputs["allow_host"] = map[string]any{"type": "boolean", "default": false, "description": "Explicitly trust host tasks with the provisioned runner user's authority"}
		inputs["host_capabilities"] = map[string]any{"type": "string", "default": "[]", "description": "JSON array of explicitly attested provisioned host capabilities; installs or enables nothing"}
	}
	if len(inputs) != 0 {
		call["inputs"] = inputs
	}
	// The caller owns token permissions. Setting only contents:read here would
	// implicitly disable a caller's explicitly granted registry-package access.
	workflow := githubWorkflow{Name: "Stoke: " + p.Config.Workflow,
		On:   map[string]any{"workflow_call": call},
		Jobs: jobs}
	var buffer bytes.Buffer
	encoder := yaml.NewEncoder(&buffer)
	encoder.SetIndent(2)
	if err := encoder.Encode(workflow); err != nil {
		return nil, err
	}
	if err := encoder.Close(); err != nil {
		return nil, err
	}
	body := buffer.Bytes()
	sum := sha256.Sum256(body)
	return append([]byte(generatedHeader+hex.EncodeToString(sum[:])+"\n"), body...), nil
}

// VerifyGenerated refuses handwritten files and body edits before regeneration.
// It proves ownership/integrity of this generated file, not source authenticity.
func VerifyGenerated(data []byte) error {
	if !bytes.HasPrefix(data, []byte(generatedHeader)) {
		return errors.New("refusing to replace a handwritten workflow; select a separate generated file")
	}
	checksum, body, ok := bytes.Cut(data[len(generatedHeader):], []byte("\n"))
	if !ok || !validDigest(string(checksum)) {
		return errors.New("invalid generated workflow header")
	}
	sum := sha256.Sum256(body)
	if hex.EncodeToString(sum[:]) != string(checksum) {
		return errors.New("generated workflow was edited; preserve those edits separately before regenerating")
	}
	return nil
}

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'"
}

// Matrix values remain literal runtime inputs. Only bounded, printable labels
// without provider expression markers are copied into provider configuration.
func matrixLabel(job Job) string {
	names := make([]string, 0, len(job.Matrix))
	for name := range job.Matrix {
		names = append(names, name)
	}
	slices.Sort(names)
	parts := make([]string, 0, len(names))
	for _, name := range names {
		parts = append(parts, name+"="+job.Matrix[name])
	}
	label := strings.Join(parts, ", ")
	if label == "" || len(label) > 256 || !utf8.ValidString(label) || strings.Contains(label, "${{") {
		return job.ID
	}
	for _, character := range label {
		if !unicode.IsPrint(character) {
			return job.ID
		}
	}
	return label
}
