#!/usr/bin/env python3
"""Generate a generic host-task matrix from a flake's actual checks inventory.

Requires an already-provisioned Nix installation. This script performs Nix
expression evaluation only; it does not build checks, install tools, or grant
host execution authority.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

HEADER = "# Generated by scripts/nix-workflow.py; Nix owns the checks inventory.\n"
HASH_PREFIX = "# stoke-nix-workflow-sha256: "
PLATFORMS = {"x86_64-linux": "linux/amd64", "aarch64-linux": "linux/arm64"}
# Declared source inputs for Stoke's checks, not a second list of check names.
STOKE_INPUTS = [
    "flake.nix", "flake.lock", "nix", "cmd", "internal", "go.mod", "go.sum",
    "LICENSE", ".github", "docs", "zensical.toml", "Justfile", "README.md",
    "CONTRIBUTING.md", "scripts/nix-workflow.py", "scripts/run-nix-check.py",
    "scripts/test-nix-workflow.py", "scripts/cache-performance.py",
    "scripts/tests/test_cache_performance.py",
]


def nix_json(nix, arguments, cwd):
    with tempfile.TemporaryFile() as output, tempfile.TemporaryFile() as errors:
        result = subprocess.run([nix, "--max-jobs", "1", "--cores", "2", "--option", "allow-import-from-derivation", "false", *arguments], cwd=cwd, stdout=output, stderr=errors, check=False)
        if output.tell() > 8 * 1024 * 1024 or errors.tell() > 8 * 1024 * 1024:
            raise ValueError("Nix discovery exceeds the 8 MiB output bound")
        output.seek(0)
        errors.seek(0)
        if result.returncode:
            raise ValueError("Nix discovery failed: " + errors.read().decode(errors="replace").strip())
        return json.loads(output.read())


def discover(nix, flake, system=None):
    location = flake.resolve(strict=True)
    reference = "path:" + str(location)
    inventory = nix_json(nix, ["eval", "--json", "--no-update-lock-file",
                             reference + "#checks", "--apply",
                             "checks: builtins.mapAttrs (_: attrs: builtins.attrNames attrs) checks"], location)
    native = nix_json(nix, ["eval", "--json", "--impure", "--expr", "builtins.currentSystem"], location)
    selected = system or native
    if not isinstance(inventory, dict) or not inventory:
        raise ValueError("flake has no check systems")
    if selected not in inventory:
        raise ValueError(f"flake has no checks for {selected!r}; supported: {', '.join(sorted(inventory))}")
    if selected not in PLATFORMS:
        raise ValueError("generic host tasks currently require native x86_64-linux or aarch64-linux")
    checks = inventory[selected]
    if not isinstance(checks, list) or not checks or not all(
            isinstance(name, str) and name and len(name) <= 512
            and not re.search(r"[\x00-\x1f\x7f]", name) for name in checks):
        raise ValueError("flake returned an invalid or empty check inventory")
    if len(checks) > 256 or len(set(checks)) != len(checks):
        raise ValueError("flake checks exceed the 256-variant limit or contain duplicates")
    return {"nativeSystem": native, "system": selected,
            "supportedSystems": sorted(inventory), "checks": sorted(checks)}


def make_workflow(discovery, inherit_env=None):
    inherited = ["HOME", "NIX_CONFIG", *(inherit_env or [])]
    inherited = list(dict.fromkeys(inherited))
    if any(not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name)
           or name.upper().startswith("STOKE_") for name in inherited):
        raise ValueError("inherit-env names must be valid, nonreserved environment names")
    return {
        "version": 1,
        "tasks": {
            "nix-checks": {
                "platform": PLATFORMS[discovery["system"]],
                "host": {
                    "tools": ["nix", "python3"],
                    "capabilities": ["nix-build"],
                    "inputs": [{"path": name, "destination": "source/" + name} for name in STOKE_INPUTS],
                    "outputs": ["reports"],
                    "inherit-env": inherited,
                    "effects": "external",
                },
                "cache": False,
                "strategy": {
                    "max-parallel": 1,
                    "fail-fast": False,
                    "matrix": {"include": [
                        {"check": check, "system": discovery["system"]}
                        for check in discovery["checks"]
                    ]},
                },
                "steps": [{"run": ["python3", "source/scripts/run-nix-check.py", "--flake", "path:source"]}],
            }
        },
    }


def render(workflow):
    # JSON is a YAML subset; no Python YAML package is required.
    body = json.dumps(workflow, indent=2, sort_keys=True) + "\n"
    return HEADER + HASH_PREFIX + hashlib.sha256(body.encode()).hexdigest() + "\n" + body


def write_generated(destination, data):
    destination = destination.absolute()
    if destination.is_symlink():
        raise ValueError("refusing to replace a symlink")
    if destination.exists():
        old = destination.read_text()
        lines = old.splitlines(keepends=True)
        if len(lines) < 3 or lines[0] != HEADER or not lines[1].startswith(HASH_PREFIX):
            raise ValueError("refusing to replace a handwritten workflow")
        recorded = lines[1][len(HASH_PREFIX):].strip()
        if recorded != hashlib.sha256("".join(lines[2:]).encode()).hexdigest():
            raise ValueError("generated workflow was edited; preserve or review those changes first")
    handle, temporary = tempfile.mkstemp(prefix=".nix-workflow-", dir=destination.parent)
    try:
        with os.fdopen(handle, "w") as output:
            output.write(data)
        os.replace(temporary, destination)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--flake", type=Path, default=Path("."),
                        help="Stoke checkout whose checks are discovered (default: cwd)")
    parser.add_argument("--nix", default="nix", help="provisioned Nix executable")
    parser.add_argument("--system", help="flake-supported native runner system (default: Nix currentSystem)")
    parser.add_argument("--inherit-env", action="append", default=[],
                        help="additional provisioned environment name to pass explicitly")
    output = parser.add_mutually_exclusive_group()
    output.add_argument("--output", type=Path, help="write a fresh or unedited owned generated workflow")
    output.add_argument("--check", type=Path, help="fail if this workflow differs from current flake discovery")
    parser.add_argument("--list", action="store_true", help="print the discovered systems/checks without YAML")
    args = parser.parse_args(argv)
    try:
        discovery = discover(args.nix, args.flake, args.system)
        if args.list:
            if args.output or args.check:
                raise ValueError("--list cannot be combined with --output or --check")
            print(json.dumps(discovery, indent=2, sort_keys=True))
            return 0
        data = render(make_workflow(discovery, args.inherit_env))
        if args.check:
            if args.check.read_text() != data:
                raise ValueError("generated Nix workflow differs; regenerate and review it")
        elif args.output:
            write_generated(args.output, data)
        else:
            sys.stdout.write(data)
        return 0
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print("nix-workflow:", error, file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
